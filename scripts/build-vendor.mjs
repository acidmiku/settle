import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

await build({
  entryPoints:['scripts/vendor-entry.js'], outfile:'src/vendor/editor.js',
  bundle:true, format:'esm', platform:'browser', target:['es2020'], minify:true,
  legalComments:'eof', banner:{js:'// Generated by npm run vendor. See LICENSES.txt for third-party licenses.'},
});
const licenses = [];
for (const [name,file] of [['highlight.js','LICENSE'],['marked','LICENSE'],['dompurify','LICENSE']]) {
  const pkg = JSON.parse(await readFile(`node_modules/${name}/package.json`, 'utf8'));
  licenses.push(`${name} ${pkg.version}\n${await readFile(`node_modules/${name}/${file}`, 'utf8')}`);
}
await writeFile('src/vendor/LICENSES.txt', licenses.join('\n\n----------------\n\n'));
