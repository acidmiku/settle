import { build } from 'esbuild';
import { readFile, writeFile, readdir } from 'node:fs/promises';

const result = await build({
  entryPoints:{editor:'scripts/vendor-entry.js', wysiwyg:'scripts/wysiwyg-entry.js'}, outdir:'src/vendor', metafile:true,
  bundle:true, format:'esm', platform:'browser', target:['es2020'], minify:true,
  legalComments:'eof', banner:{js:'// Generated by npm run vendor. See LICENSES.txt for third-party licenses.'},
});
const licenses = [];
const packages = new Set(Object.keys(result.metafile.inputs).filter(file => file.startsWith('node_modules/')).map(file => {
  const parts = file.split('/');
  const index = parts.lastIndexOf('node_modules');
  return parts.slice(0, index + (parts[index + 1].startsWith('@') ? 3 : 2)).join('/');
}));
for (const dir of [...packages].sort()) {
  const pkg = JSON.parse(await readFile(`${dir}/package.json`, 'utf8'));
  const file = (await readdir(dir)).find(name => /^licen[cs]e(?:\.md|\.txt)?$/i.test(name));
  if (!file) throw new Error(`Missing bundled license for ${pkg.name}`);
  licenses.push(`${pkg.name} ${pkg.version}\n${await readFile(`${dir}/${file}`, 'utf8')}`);
}
await writeFile('src/vendor/LICENSES.txt', licenses.join('\n\n----------------\n\n'));
